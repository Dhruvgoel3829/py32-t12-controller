static uint8_t font_index(char c)
{
  if (c >= 'a' && c <= 'z') c -= 32;
  if (c < 0x20 || c > 0x5A) c = '?';
  return (uint8_t)(c - 0x20);
}

uint8_t oled_text_width(const char *text, uint8_t scale)
{
  uint8_t length = 0;
  while (*text++) length++;
  return (uint8_t)(length * 6 * scale);
}

void oled_text(uint8_t x, uint8_t y, const char *text, uint8_t scale)
{
  while (*text) {
    uint8_t index = font_index(*text++);
    for (uint8_t column = 0; column < 5; column++) {
      uint8_t bits = font5x7[index][column];
      for (uint8_t row = 0; row < 7; row++) {
        if (bits & (1U << row))
          oled_fill(x + column * scale, y + row * scale, scale, scale);
      }
    }
    x += 6 * scale;
  }
}

void oled_text_center(uint8_t y, const char *text, uint8_t scale)
{
  uint8_t width = oled_text_width(text, scale);
  oled_text((OLED_WIDTH - width) / 2, y, text, scale);
}
