#include "oled.h"
#include "py32f0xx_ll_bus.h"
#include "py32f0xx_ll_gpio.h"
#include "py32f0xx_ll_utils.h"

#define OLED_SCL_PORT GPIOA
#define OLED_SCL_PIN  LL_GPIO_PIN_3
#define OLED_SDA_PORT GPIOA
#define OLED_SDA_PIN  LL_GPIO_PIN_2
#define OLED_ADDR_0   0x78
#define OLED_ADDR_1   0x7A

static uint8_t oled_buffer[OLED_WIDTH * OLED_HEIGHT / 8];
static uint8_t oled_addr = OLED_ADDR_0;

volatile uint8_t oled_ack_78;
volatile uint8_t oled_ack_7a;
volatile uint8_t oled_ready;
volatile uint32_t oled_nack_count;

static inline void oled_delay(void)
{
  for (volatile uint8_t i = 0; i < 8; i++) __NOP();
}

#define SCL_H() LL_GPIO_SetOutputPin(OLED_SCL_PORT, OLED_SCL_PIN)
#define SCL_L() LL_GPIO_ResetOutputPin(OLED_SCL_PORT, OLED_SCL_PIN)
#define SDA_H() LL_GPIO_SetOutputPin(OLED_SDA_PORT, OLED_SDA_PIN)
#define SDA_L() LL_GPIO_ResetOutputPin(OLED_SDA_PORT, OLED_SDA_PIN)

static void i2c_start(void)
{
  SDA_H();
  SCL_H();
  oled_delay();
  SDA_L();
  oled_delay();
  SCL_L();
}

static void i2c_stop(void)
{
  SDA_L();
  oled_delay();
  SCL_H();
  oled_delay();
  SDA_H();
  oled_delay();
}

static uint8_t i2c_write(uint8_t value)
{
  for (uint8_t i = 0; i < 8; i++) {
    if (value & 0x80) SDA_H();
    else SDA_L();
    oled_delay();
    SCL_H();
    oled_delay();
    SCL_L();
    value <<= 1;
  }
  SDA_H();
  oled_delay();
  SCL_H();
  oled_delay();
  uint8_t ack = LL_GPIO_IsInputPinSet(OLED_SDA_PORT, OLED_SDA_PIN) ? 0 : 1;
  if (!ack) oled_nack_count++;
  SCL_L();
  return ack;
}

static uint8_t i2c_probe(uint8_t addr)
{
  i2c_start();
  uint8_t ack = i2c_write(addr);
  i2c_stop();
  return ack;
}

static void oled_command(uint8_t value)
{
  i2c_start();
  i2c_write(oled_addr);
  i2c_write(0x00);
  i2c_write(value);
  i2c_stop();
}

static void oled_commands(const uint8_t *values, uint8_t count)
{
  i2c_start();
  i2c_write(oled_addr);
  i2c_write(0x00);
  for (uint8_t i = 0; i < count; i++) i2c_write(values[i]);
  i2c_stop();
}

static void oled_set_position(uint8_t column, uint8_t page)
{
  oled_command(0xB0 | (page & 0x07));
  oled_command(column & 0x0F);
  oled_command(0x10 | (column >> 4));
}

static void i2c_init(void)
{
  LL_IOP_GRP1_EnableClock(LL_IOP_GRP1_PERIPH_GPIOA);

  LL_GPIO_InitTypeDef gpio = {0};
  gpio.Pin = OLED_SCL_PIN | OLED_SDA_PIN;
  gpio.Mode = LL_GPIO_MODE_OUTPUT;
  gpio.OutputType = LL_GPIO_OUTPUT_OPENDRAIN;
  gpio.Pull = LL_GPIO_PULL_UP;
  gpio.Speed = LL_GPIO_SPEED_FREQ_HIGH;
  LL_GPIO_Init(OLED_SCL_PORT, &gpio);

  SCL_H();
  SDA_H();
}

void oled_init(void)
{
  static const uint8_t sequence[] = {
    0xAE, 0xD5, 0x80, 0xA8, 0x3F, 0xD3, 0x00, 0x40,
    0x8D, 0x14, 0x20, 0x02, 0xA1, 0xC8, 0xDA, 0x12,
    0x81, 0x7F, 0xD9, 0xF1, 0xDB, 0x40, 0xA4, 0xA6, 0xAF
  };

  i2c_init();
  LL_mDelay(50);

  oled_ack_78 = i2c_probe(OLED_ADDR_0);
  oled_ack_7a = i2c_probe(OLED_ADDR_1);
  if (oled_ack_78) {
    oled_addr = OLED_ADDR_0;
    oled_ready = 1;
  } else if (oled_ack_7a) {
    oled_addr = OLED_ADDR_1;
    oled_ready = 1;
  }

  oled_commands(sequence, sizeof(sequence));
  LL_mDelay(100);
  oled_clear();
  oled_flush();
}

void oled_flip(uint8_t flipped)
{
  oled_command(flipped ? 0xA0 : 0xA1);
  oled_command(flipped ? 0xC0 : 0xC8);
}

void oled_clear(void)
{
  for (uint16_t i = 0; i < sizeof(oled_buffer); i++) oled_buffer[i] = 0;
}

static void oled_pixel(uint8_t x, uint8_t y)
{
  if (x >= OLED_WIDTH || y >= OLED_HEIGHT) return;
  oled_buffer[(y >> 3) * OLED_WIDTH + x] |= (uint8_t)(1U << (y & 7));
}

static void oled_fill(uint8_t x, uint8_t y, uint8_t width, uint8_t height)
{
  for (uint8_t yy = 0; yy < height; yy++)
    for (uint8_t xx = 0; xx < width; xx++)
      oled_pixel(x + xx, y + yy);
}

void oled_flush(void)
{
  for (uint8_t page = 0; page < 8; page++) {
    oled_set_position(0, page);
    i2c_start();
    i2c_write(oled_addr);
    i2c_write(0x40);
    for (uint8_t column = 0; column < OLED_WIDTH; column++)
      i2c_write(oled_buffer[page * OLED_WIDTH + column]);
    i2c_stop();
  }
}

